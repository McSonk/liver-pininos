#!/usr/bin/env python3
"""
Test-time evaluation entry point for HCC tumour segmentation thesis.

This script loads previously generated raw predictions (NIfTI format) and 
ground truth labels, applies optional morphological post-processing, and 
computes clinical metrics (Dice, HD95) in the original scanner space. 
It then generates a thesis-ready report.

Usage:
    python do_evaluation.py --post-process
"""
print("[do_evaluation.py] Importing dependencies... (This may take a moment)")
import argparse
import logging
import os
import sys
from pathlib import Path

import torch
from monai.utils import set_determinism

from idssp.sonk import config
from idssp.sonk.disk.loader import DataCollector
from idssp.sonk.model.evaluator import MetricsEvaluator
from idssp.sonk.utils.logger import (configure_logging, get_logger,
                                     install_global_exception_handlers)

# For reproducibility
set_determinism(seed=42)

def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Run test-time evaluation for HCC tumour segmentation",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument(
        "--pred-dir", "-p",
        type=str,
        default=None,
        help="Directory containing the raw NIfTI predictions generated by do_inference.py. "
             "Defaults to <RUN_DIR>/test_predictions."
    )
    parser.add_argument(
        "--post-process", "-pp",
        action="store_true",
        help="Whether to apply morphological post-processing (e.g., Largest Connected "
             "Component filtering) to the predicted segmentation maps before metric computation."
    )
    parser.add_argument(
        "--output-dir", "-o",
        type=str,
        default=None,
        help="Directory to save the CSV reports. Defaults to <RUN_DIR>/reports."
    )
    return parser.parse_args()

def log_environment_info(config_obj: config.Config, logger: logging.Logger) -> None:
    '''Logs detailed information about the runtime environment, including PyTorch version,
    CUDA availability and devices, and key configuration parameters.'''
    cuda_properties = None
    logger.info("Model (code) Version: %s", config_obj.VERSION)
    logger.info("Environment Information:")
    logger.info("PyTorch version: %s", torch.__version__)
    logger.info("CUDA available: %s", torch.cuda.is_available())
    if torch.cuda.is_available():
        # 1. Get PyTorch device properties (logical index 0 due to CUDA_VISIBLE_DEVICES)
        cuda_properties = torch.cuda.get_device_properties(0)
        logger.info("CUDA device count: %d", torch.cuda.device_count())
        for i in range(torch.cuda.device_count()):
            logger.info("CUDA device %d: %s", i, torch.cuda.get_device_name(i))
        logger.info("Available GPU memory (GB): %d", cuda_properties.total_memory // (1024 ** 3))
    else:
        logger.info("No CUDA devices available.")

    logger.info("Available CPU cores: %s", os.cpu_count())
    logger.info("PyTorch intra-op threads: %d", torch.get_num_threads())
    logger.info("Available CPU memory (GB): %.2f", config_obj.cpu_memory)
    logger.info("Available container memory (GB): %.2f", config_obj.container_memory)
    logger.info("Device: %s", config_obj.DEVICE)
    logger.info("Data Root: %s", config_obj.CT_TEST)
    logger.info("Log Dir: %s", config_obj.LOG_DIR)

def _main(args: argparse.Namespace):
    cfg = config.init(mode=config.Mode.TEST)
    configure_logging(cfg)
    # Initialize logger
    logger = get_logger(__name__)
    # Install global hooks (for logging unhandled exceptions)
    install_global_exception_handlers(logger)

    pred_dir = Path(args.pred_dir) if args.pred_dir else cfg.RUN_DIR / "test_predictions"
    output_dir = Path(args.output_dir) if args.output_dir else cfg.RUN_DIR / "reports"
    post_process = args.post_process

    if not pred_dir.exists():
        logger.error("Prediction directory not found: %s", pred_dir)
        logger.error("Please run do_inference.py first to generate the raw predictions.")
        return 1

    logger.info("This is the test-time evaluation script for tumour segmentation. "
                "It will load previously generated predictions, compute clinical metrics "
                "in the original scanner space, and generate a thesis-ready report.")
    logger.info("Loading predictions from: %s", pred_dir)
    logger.info("Reports will be saved to: %s", output_dir)

    if post_process:
        logger.info("Post-processing of predictions is ENABLED.")
    else:
        logger.info("Post-processing of predictions is DISABLED; "
                    "raw model outputs will be used for metrics.")

    log_environment_info(cfg, logger)

    logger.info("[Evaluation] Reading directories...")
    loader = DataCollector()
    loader.read_dir(cfg.CT_TEST, ds_source='LiTS')
    test_files = loader.extract_images_and_labels()

    if not test_files:
        logger.error(
            "No valid test image/label pairs were found in %s. "
            "Check the test dataset configuration and contents before running evaluation.",
            cfg.CT_TEST,
        )
        return 1

    logger.debug("Done! Some information about the environment:")
    logger.debug("ISO spacing: %s", cfg.ISO_SPACING)
    logger.debug("Training patch size: %s", cfg.TRAIN_PATCH_SIZE)

    logger.info("%d test files found.", len(test_files))
    for file in test_files:
        logger.debug(file)

    evaluator = MetricsEvaluator(post_process=post_process)
    results = evaluator.evaluate(test_files, pred_dir)
    report_path = evaluator.generate_report(results, output_dir)

    logger.info("Evaluation complete. Report saved to: %s", report_path)
    return 0


if __name__ == "__main__":
    exit_code = _main(_parse_args())
    sys.exit(exit_code)