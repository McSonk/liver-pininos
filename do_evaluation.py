#!/usr/bin/env python3
"""
Test-time evaluation entry point for HCC tumour segmentation thesis.

This script loads previously generated raw predictions (NIfTI format) and 
ground truth labels, applies optional morphological post-processing, and 
computes clinical metrics (Dice, HD95) in the original scanner space. 
It then generates a thesis-ready report.

Usage:
    python do_evaluation.py
    python do_evaluation.py --pred-dir /path/to/specific/run/test_predictions
"""
print("[do_evaluation.py] Importing dependencies... (This may take a moment)")
import argparse
import sys
from pathlib import Path
from typing import Optional

from monai.utils import set_determinism

from idssp.sonk import config
from idssp.sonk.disk.loader import DataCollector
from idssp.sonk.model.evaluator import MetricsEvaluator
from idssp.sonk.utils.logger import (configure_logging, get_logger,
                                     install_global_exception_handlers)

# For reproducibility
set_determinism(seed=42)

def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Run test-time evaluation for HCC tumour segmentation",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument(
        "--pred-dir", "-p",
        type=str,
        default=None,
        help="Directory containing the raw NIfTI predictions generated by do_inference.py. "
             "If omitted, automatically resolves to the most recent run directory "
             "in OUTPUT_DIR that contains a 'test_predictions' folder."
    )
    parser.add_argument(
        "--output-dir", "-o",
        type=str,
        default=None,
        help="Directory to save the CSV reports. Defaults to <RUN_DIR>/reports."
    )
    return parser.parse_args()

def _find_latest_test_predictions_dir(output_dir: Path) -> Optional[Path]:
    """
    Scan the output directory for the most recently modified run directory 
    that contains a non-empty 'test_predictions' subdirectory.
    
    This solves the cross-machine execution problem: when predictions are 
    generated on a server and evaluated locally, the local config.py generates 
    a new timestamped RUN_DIR. This helper finds the actual downloaded predictions.
    """
    if not output_dir.exists():
        return None

    candidates = []
    # Look for directories matching the test run pattern (e.g., <VERSION>-20260806_120000_test)
    for run_dir in output_dir.iterdir():
        if run_dir.is_dir() and run_dir.name.endswith("_test"):
            pred_dir = run_dir / "test_predictions"
            # Ensure the directory exists and actually contains files
            if pred_dir.is_dir() and any(pred_dir.iterdir()):
                candidates.append((pred_dir.stat().st_mtime, pred_dir))

    if not candidates:
        return None

    # Sort by modification time descending to get the most recent
    candidates.sort(key=lambda x: x[0], reverse=True)
    return candidates[0][1]


def _main(args: argparse.Namespace):
    cfg = config.init(mode=config.Mode.TEST)
    configure_logging(cfg)
    # Initialize logger
    logger = get_logger(__name__)
    # Install global hooks (for logging unhandled exceptions)
    install_global_exception_handlers(logger)

    # --- Prediction Directory Resolution ---
    pred_dir = Path(args.pred_dir) if args.pred_dir else None

    if pred_dir is None:
        logger.info("No --pred-dir specified. Searching for the most recent test predictions in %s...", cfg.OUTPUT_DIR)
        latest_pred_dir = _find_latest_test_predictions_dir(cfg.OUTPUT_DIR)
        if latest_pred_dir is None:
            logger.error(
                "Could not auto-resolve prediction directory. "
                "No previous runs with 'test_predictions' were found in %s. "
                "Please specify the path explicitly using --pred-dir.",
                cfg.OUTPUT_DIR
            )
            return 1
        pred_dir = latest_pred_dir
        logger.info("Auto-resolved prediction directory: %s", pred_dir)

    if not pred_dir.exists():
        logger.error("Prediction directory not found: %s", pred_dir)
        logger.error("Please run do_inference.py first to generate the raw predictions.")
        return 1
    # ---------------------------------------

    output_dir = Path(args.output_dir) if args.output_dir else cfg.RUN_DIR / "reports"

    logger.info("This is the test-time evaluation script for tumour segmentation. "
                "It will load previously generated predictions, compute clinical metrics "
                "in the original scanner space (both raw and post-processed), and generate a thesis-ready report.")
    logger.info("Loading predictions from: %s", pred_dir)
    logger.info("Reports will be saved to: %s", output_dir)

    logger.info("[Evaluation] Reading directories...")
    loader = DataCollector()
    loader.read_dir(cfg.CT_TEST, ds_source='LiTS')
    test_files = loader.extract_images_and_labels()

    if not test_files:
        logger.error(
            "No valid test image/label pairs were found in %s. "
            "Check the test dataset configuration and contents before running evaluation.",
            cfg.CT_TEST,
        )
        return 1

    logger.debug("Done! Some information about the environment:")
    logger.debug("ISO spacing: %s", cfg.ISO_SPACING)
    logger.debug("Training patch size: %s", cfg.TRAIN_PATCH_SIZE)

    logger.info("%d test files found.", len(test_files))
    for file in test_files:
        logger.debug(file)

    # Evaluator now computes both raw and post-processed metrics in a single pass
    evaluator = MetricsEvaluator()
    results_dict = evaluator.evaluate(test_files, pred_dir)

    if not results_dict or all(df.empty for df in results_dict.values()):
        logger.error("Evaluation aborted: No valid predictions were processed.")
        return 1

    report_path = evaluator.generate_report(results_dict, output_dir)

    logger.info("Evaluation complete. Reports saved to: %s", report_path)
    return 0


if __name__ == "__main__":
    exit_code = _main(_parse_args())
    sys.exit(exit_code)
